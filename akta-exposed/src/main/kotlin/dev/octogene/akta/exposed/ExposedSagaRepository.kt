// ---- Tables. The schema itself (constraints, indexes) is in schema.sql, applied by Flyway. ------
// Internal: they belong to this repository. Query the tables with SQL (see the events reference).

internal object SagaTable : Table("saga") {
    val id = uuid("id")               // generated by SagaEngine.create (UUID v7)
    val type = text("type")
    val businessKey = text("business_key")
    val state = text("state")
    val stepIndex = integer("step_index")
    val stepStatus = text("step_status")
    val attempts = integer("attempts")
    val checkFailures = integer("check_failures")
    val nextAttemptAt = timestampWithTimeZone("next_attempt_at")
    val lockedUntil = timestampWithTimeZone("locked_until").nullable()
    val lastError = text("last_error").nullable()
    val traceparent = text("traceparent").nullable()
    val input = text("input").nullable()
    val cancelRequestedAt = timestampWithTimeZone("cancel_requested_at").nullable()
    val cancelReason = text("cancel_reason").nullable()
    val failureReason = text("failure_reason").nullable()
    val stuckReason = text("stuck_reason").nullable()
    val stuckAt = timestampWithTimeZone("stuck_at").nullable()
    val keySince = timestampWithTimeZone("key_since").nullable()
    val keyGeneration = integer("key_generation")
    val resumeFailures = integer("resume_failures")
    val stuckFrom = text("stuck_from").nullable()
    val callAction = text("call_action").nullable()
    val createdAt = timestampWithTimeZone("created_at")
    val updatedAt = timestampWithTimeZone("updated_at")
    override val primaryKey = PrimaryKey(id)
}

/** References returned by completed steps. */
internal object SagaStepResultTable : Table("saga_step_result") {
    val sagaId = uuid("saga_id")
    val stepIndex = integer("step_index")
    val stepName = text("step_name")
    val output = text("output").nullable()
    val doneAt = timestampWithTimeZone("done_at")
    val compensatedAt = timestampWithTimeZone("compensated_at").nullable()
    override val primaryKey = PrimaryKey(sagaId, stepIndex)
}

/** Signals received for signal steps: one per name and saga. */
internal object SagaSignalTable : Table("saga_signal") {
    val sagaId = uuid("saga_id")
    val signalName = text("signal_name")
    val value = text("value")
    val receivedAt = timestampWithTimeZone("received_at")
    override val primaryKey = PrimaryKey(sagaId, signalName)
}

/** History: every call, check, compensation and manual action. */
internal object SagaLogTable : Table("saga_log") {
    val id = long("id").autoIncrement()
    val sagaId = uuid("saga_id")
    val at = timestampWithTimeZone("at")
    val stepIndex = integer("step_index")
    val stepName = text("step_name").nullable()
    val event = text("event")
    val detail = text("detail").nullable()
    val actor = text("actor").nullable()
    val traceId = text("trace_id").nullable()
    override val primaryKey = PrimaryKey(id)
}

/**
 * PostgreSQL implementation with Exposed (DSL). Uses the current Exposed transaction, so
 * [dev.octogene.akta.SagaEngine.create] can run inside the application's own transaction.
 */
public class ExposedSagaRepository : SagaRepository {

    /**
     * ON CONFLICT DO NOTHING instead of catching the unique violation: in PostgreSQL an error aborts the
     * whole transaction, and this runs inside the caller's business transaction, which must stay usable
     * after a [DuplicateSagaException] (e.g. to answer 409 and go on).
     */
    override fun insert(record: SagaRecord, now: Instant) {
        val inserted = SagaTable.insertIgnore {
            it[id] = record.id
            it[type] = record.type
            it[businessKey] = record.key
            it[createdAt] = record.createdAt.utc()
            it[input] = record.input                // written once: write() below never touches it
            write(it, record, now)
        }.insertedCount
        if (inserted == 0) {
            // The transaction is still usable (no error was raised): find the saga that holds the key. ON CONFLICT
            // waited for a concurrent insert to commit, so this new statement sees it, unless it finished meanwhile.
            val existing = SagaTable.select(SagaTable.id)
                .where { (SagaTable.businessKey eq record.key) and (SagaTable.state inList UNFINISHED) }
                .singleOrNull()?.get(SagaTable.id)
            throw DuplicateSagaException(record.key, existingSagaId = existing)
        }
    }

    override fun lock(id: Uuid, skipLocked: Boolean): SagaRecord? {
        val query = SagaTable.selectAll().where { SagaTable.id eq id }
        val locked = if (skipLocked) {
            query.forUpdate(ForUpdateOption.PostgreSQL.ForUpdate(ForUpdateOption.PostgreSQL.MODE.SKIP_LOCKED))
        } else {
            query.forUpdate()
        }
        return locked.singleOrNull()?.toRecord()
    }

    override fun find(id: Uuid): SagaRecord? =
        SagaTable.selectAll().where { SagaTable.id eq id }.singleOrNull()?.toRecord()

    override fun save(record: SagaRecord, now: Instant) {
        SagaTable.update({ SagaTable.id eq record.id }) { write(it, record, now) }
    }

    override fun findDue(now: Instant, limit: Int, types: Collection<String>): List<Uuid> =
        SagaTable.select(SagaTable.id)
            .where {
                (SagaTable.state inList UNFINISHED) and
                    (SagaTable.type inList types) and
                    (SagaTable.stepStatus neq StepStatus.STUCK.name) and
                    (SagaTable.nextAttemptAt lessEq now.utc())
            }
            .orderBy(SagaTable.nextAttemptAt)
            .limit(limit)
            .map { it[SagaTable.id] }

    override fun stepResults(sagaId: Uuid): List<StepResultRecord> =
        SagaStepResultTable.selectAll()
            .where { SagaStepResultTable.sagaId eq sagaId }
            .orderBy(SagaStepResultTable.stepIndex)
            .map {
                StepResultRecord(
                    stepIndex = it[SagaStepResultTable.stepIndex],
                    stepName = it[SagaStepResultTable.stepName],
                    output = it[SagaStepResultTable.output],
                    doneAt = it[SagaStepResultTable.doneAt].toKotlin(),
                    compensatedAt = it[SagaStepResultTable.compensatedAt]?.toKotlin(),
                )
            }

    override fun results(sagaId: Uuid): Map<String, String?> =
        SagaStepResultTable.selectAll()
            .where { (SagaStepResultTable.sagaId eq sagaId) and SagaStepResultTable.compensatedAt.isNull() }
            .associate { it[SagaStepResultTable.stepName] to it[SagaStepResultTable.output] }

    override fun saveResult(sagaId: Uuid, stepIndex: Int, stepName: String, output: String?, now: Instant) {
        SagaStepResultTable.upsert {
            it[this.sagaId] = sagaId
            it[this.stepIndex] = stepIndex
            it[this.stepName] = stepName
            it[this.output] = output
            it[doneAt] = now.utc()
            it[compensatedAt] = null
        }
    }

    override fun markCompensated(sagaId: Uuid, stepIndex: Int, now: Instant) {
        SagaStepResultTable.update({
            (SagaStepResultTable.sagaId eq sagaId) and (SagaStepResultTable.stepIndex eq stepIndex)
        }) {
            it[compensatedAt] = now.utc()
        }
    }

    override fun log(entry: SagaLogEntry) {
        SagaLogTable.insert {
            it[sagaId] = entry.sagaId
            it[at] = entry.at.utc()
            it[stepIndex] = entry.stepIndex
            it[stepName] = entry.stepName
            it[event] = entry.event
            it[detail] = entry.detail?.take(SagaRepository.MAX_TEXT)
            it[actor] = entry.actor
            it[traceId] = entry.traceId
        }
    }

    private fun write(s: UpdateBuilder<*>, row: SagaRecord, now: Instant) {
        s[SagaTable.state] = row.state.name
        s[SagaTable.stepIndex] = row.stepIndex
        s[SagaTable.stepStatus] = row.stepStatus.name
        s[SagaTable.attempts] = row.attempts
        s[SagaTable.checkFailures] = row.checkFailures
        s[SagaTable.cancelRequestedAt] = row.cancelRequestedAt?.utc()
        s[SagaTable.cancelReason] = row.cancelReason
        s[SagaTable.failureReason] = row.failureReason?.take(SagaRepository.MAX_TEXT)
        s[SagaTable.stuckReason] = row.stuckReason?.name
        s[SagaTable.stuckAt] = row.stuckAt?.utc()
        s[SagaTable.keySince] = row.keySince?.utc()
        s[SagaTable.keyGeneration] = row.keyGeneration
        s[SagaTable.resumeFailures] = row.resumeFailures
        s[SagaTable.stuckFrom] = row.stuckFrom?.name
        s[SagaTable.callAction] = row.callAction?.name
        s[SagaTable.nextAttemptAt] = row.nextAttemptAt.utc()
        s[SagaTable.lockedUntil] = row.lockedUntil?.utc()
        s[SagaTable.lastError] = row.lastError?.take(SagaRepository.MAX_TEXT)
        s[SagaTable.traceparent] = row.traceparent
        s[SagaTable.updatedAt] = now.utc()
    }

    private fun ResultRow.toRecord() = SagaRecord(
        id = this[SagaTable.id],
        type = this[SagaTable.type],
        key = this[SagaTable.businessKey],
        state = SagaState.valueOf(this[SagaTable.state]),
        stepIndex = this[SagaTable.stepIndex],
        stepStatus = StepStatus.valueOf(this[SagaTable.stepStatus]),
        attempts = this[SagaTable.attempts],
        checkFailures = this[SagaTable.checkFailures],
        nextAttemptAt = this[SagaTable.nextAttemptAt].toKotlin(),
        lockedUntil = this[SagaTable.lockedUntil]?.toKotlin(),
        lastError = this[SagaTable.lastError],
        traceparent = this[SagaTable.traceparent],
        createdAt = this[SagaTable.createdAt].toKotlin(),
        input = this[SagaTable.input],
        cancelRequestedAt = this[SagaTable.cancelRequestedAt]?.toKotlin(),
        cancelReason = this[SagaTable.cancelReason],
        failureReason = this[SagaTable.failureReason],
        stuckReason = this[SagaTable.stuckReason]?.let(StuckReason::valueOf),
        stuckAt = this[SagaTable.stuckAt]?.toKotlin(),
        keySince = this[SagaTable.keySince]?.toKotlin(),
        keyGeneration = this[SagaTable.keyGeneration],
        resumeFailures = this[SagaTable.resumeFailures],
        stuckFrom = this[SagaTable.stuckFrom]?.let(StepStatus::valueOf),
        callAction = this[SagaTable.callAction]?.let(CallAction::valueOf),
    )

    private fun ResultRow.toEntry() = SagaLogEntry(
        sagaId = this[SagaLogTable.sagaId],
        at = this[SagaLogTable.at].toKotlin(),
        stepIndex = this[SagaLogTable.stepIndex],
        stepName = this[SagaLogTable.stepName],
        event = this[SagaLogTable.event],
        detail = this[SagaLogTable.detail],
        actor = this[SagaLogTable.actor],
        traceId = this[SagaLogTable.traceId],
    )

    override fun purgeFinished(before: Instant, limit: Int): Int {
        // SKIP LOCKED: a row locked by anyone else is simply left for the next run.
        val ids = SagaTable.select(SagaTable.id)
            .where { (SagaTable.state inList FINISHED) and (SagaTable.updatedAt less before.utc()) }
            .orderBy(SagaTable.updatedAt)
            .limit(limit)
            .forUpdate(ForUpdateOption.PostgreSQL.ForUpdate(ForUpdateOption.PostgreSQL.MODE.SKIP_LOCKED))
            .map { it[SagaTable.id] }
        if (ids.isEmpty()) return 0
        // Children first: saga_log and saga_step_result reference saga.
        SagaLogTable.deleteWhere { SagaLogTable.sagaId inList ids }
        SagaSignalTable.deleteWhere { SagaSignalTable.sagaId inList ids }
        SagaStepResultTable.deleteWhere { SagaStepResultTable.sagaId inList ids }
        return SagaTable.deleteWhere { SagaTable.id inList ids }
    }

    override fun saveSignal(sagaId: Uuid, name: String, value: String, now: Instant): Boolean =
        SagaSignalTable.insertIgnore {
            // ON CONFLICT DO NOTHING: the first signal of a name wins
            it[this.sagaId] = sagaId
            it[signalName] = name
            it[this.value] = value
            it[receivedAt] = now.utc()
        }.insertedCount > 0

    override fun signal(sagaId: Uuid, name: String): String? =
        SagaSignalTable.select(SagaSignalTable.value)
            .where { (SagaSignalTable.sagaId eq sagaId) and (SagaSignalTable.signalName eq name) }
            .singleOrNull()
            ?.get(SagaSignalTable.value)

    // ---- Reads for operators: each one on a partial index (saga_stuck, saga_due) or a log index ----------

    override fun findStuck(limit: Int, types: Collection<String>?, after: StuckCursor?): List<SagaRecord> =
        SagaTable.selectAll()
            .where {
                var op: Op<Boolean> = (SagaTable.stepStatus eq StepStatus.STUCK.name) and ofTypes(types)
                if (after != null) {
                    // (stuck_at, id) > (?, ?): a row comparison, which PostgreSQL resolves as one range of the
                    // saga_stuck index, unlike the equivalent OR.
                    val cursor = Row(
                        QueryParameter(after.stuckAt.utc(), SagaTable.stuckAt.columnType),
                        QueryParameter(after.id, SagaTable.id.columnType),
                    )
                    op = op and object : ComparisonOp(Row(SagaTable.stuckAt, SagaTable.id), cursor, ">") {}
                }
                op
            }
            .orderBy(SagaTable.stuckAt to SortOrder.ASC, SagaTable.id to SortOrder.ASC)
            .limit(limit)
            .map { it.toRecord() }

    override fun findByKey(key: String, limit: Int): List<SagaRecord> {
        // The unfinished one first (at most one, by saga_one_running_per_key), then the finished ones newest first: two
        // queries, each on its partial index. One ordered by created_at alone could put a finished saga first, when
        // the pod that created the next one has a clock behind the one that finished it.
        val unfinished = SagaTable.selectAll()
            .where { (SagaTable.businessKey eq key) and (SagaTable.state inList UNFINISHED) }
            .map { it.toRecord() }
        if (unfinished.size >= limit) return unfinished.take(limit)
        return unfinished + SagaTable.selectAll()
            .where { (SagaTable.businessKey eq key) and (SagaTable.state inList FINISHED) }
            .orderBy(SagaTable.createdAt to SortOrder.DESC, SagaTable.id to SortOrder.DESC)
            .limit(limit - unfinished.size)
            .map { it.toRecord() }
    }

    override fun history(sagaId: Uuid): List<SagaLogEntry> =
        SagaLogTable.selectAll()
            .where { SagaLogTable.sagaId eq sagaId }
            .orderBy(SagaLogTable.at to SortOrder.ASC, SagaLogTable.id to SortOrder.ASC)
            .map { it.toEntry() }

    // The index saga_log_saga, read backwards: only the entries returned.
    override fun recentHistory(sagaId: Uuid, limit: Int): List<SagaLogEntry> =
        SagaLogTable.selectAll()
            .where { SagaLogTable.sagaId eq sagaId }
            .orderBy(SagaLogTable.at to SortOrder.DESC, SagaLogTable.id to SortOrder.DESC)
            .limit(limit)
            .map { it.toEntry() }
            .reversed()

    override fun historyByTrace(traceId: String, limit: Int): List<SagaLogEntry> =
        SagaLogTable.selectAll()
            .where { SagaLogTable.traceId eq traceId }
            .orderBy(SagaLogTable.at to SortOrder.ASC, SagaLogTable.id to SortOrder.ASC)
            .limit(limit)
            .map { it.toEntry() }

    /**
     * One query: the counts read every unfinished saga anyway, so the oldest dates come from the same
     * scan, as a minimum per group (a few dozen groups at most), combined here.
     */
    override fun stats(now: Instant, types: Collection<String>?): SagaStats {
        val count = SagaTable.id.count()
        val oldestCreated = SagaTable.createdAt.min()
        val oldestNext = SagaTable.nextAttemptAt.min()
        val groups = SagaTable
            .select(SagaTable.state, SagaTable.stepStatus, SagaTable.stuckReason, count, oldestCreated, oldestNext)
            .where { (SagaTable.state inList UNFINISHED) and ofTypes(types) }
            .groupBy(SagaTable.state, SagaTable.stepStatus, SagaTable.stuckReason)
            .map {
                StatsGroup(
                    state = SagaState.valueOf(it[SagaTable.state]),
                    status = StepStatus.valueOf(it[SagaTable.stepStatus]),
                    reason = it[SagaTable.stuckReason]?.let(StuckReason::valueOf),
                    count = it[count],
                    oldestCreated = it[oldestCreated]?.toKotlin(),
                    oldestNext = it[oldestNext]?.toKotlin(),
                )
            }
        val byStatus = groups.groupBy { it.state to it.status }.mapValues { (_, g) -> g.sumOf { it.count } }
        val stuck = groups.filter { it.status == StepStatus.STUCK }
        val byReason = stuck.groupBy { checkNotNull(it.reason) }.mapValues { (_, g) -> g.sumOf { it.count } }
        val active = groups - stuck.toSet()
        val oldestUnfinished = active.mapNotNull { it.oldestCreated }.minOrNull()
        // The smallest next attempt, if it is due, is the oldest due one; if it is not, none is due.
        val oldestDue = active.mapNotNull { it.oldestNext }.minOrNull()?.takeIf { it <= now }
        return SagaStats(byStatus, byReason, oldestUnfinished, oldestDue)
    }

    private class StatsGroup(
        val state: SagaState,
        val status: StepStatus,
        val reason: StuckReason?,
        val count: Long,
        val oldestCreated: Instant?,
        val oldestNext: Instant?,
    )

    /** A row value, `(a, b, …)`, for row comparisons. */
    private class Row(vararg val parts: Expression<*>) : Expression<Any>() {
        override fun toQueryBuilder(queryBuilder: QueryBuilder) = queryBuilder {
            parts.toList().appendTo(separator = ", ", prefix = "(", postfix = ")") { append(it) }
        }
    }

    private fun ofTypes(types: Collection<String>?): Op<Boolean> = if (types == null) Op.TRUE else SagaTable.type inList types

    private companion object {
        val UNFINISHED = listOf(SagaState.RUNNING.name, SagaState.COMPENSATING.name, SagaState.FINISHING.name)
        val FINISHED = listOf(SagaState.COMPLETED.name, SagaState.FAILED.name)
    }
}

// timestampWithTimeZone is java.time.OffsetDateTime, even in exposed-kotlin-datetime (its timestamp() is
// kotlin.time.Instant but maps to a column WITHOUT time zone, unlike the timestamptz schema): convert here.
private fun Instant.utc(): OffsetDateTime = toJavaInstant().atOffset(ZoneOffset.UTC)

private fun OffsetDateTime.toKotlin(): Instant = toInstant().toKotlinInstant()
