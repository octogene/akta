// ---- Tables. The schema itself (constraints, indexes) is in schema.sql, applied by Flyway. ------

object SagaTable : Table("saga") {
    val id = uuid("id")               // generated by SagaEngine.create (UUID v7)
    val type = text("type")
    val businessKey = text("business_key")
    val state = text("state")
    val stepIndex = integer("step_index")
    val stepStatus = text("step_status")
    val attempts = integer("attempts")
    val checkFailures = integer("check_failures")
    val nextAttemptAt = timestampWithTimeZone("next_attempt_at")
    val lockedUntil = timestampWithTimeZone("locked_until").nullable()
    val lastError = text("last_error").nullable()
    val traceparent = text("traceparent").nullable()
    val input = text("input").nullable()
    val cancelRequestedAt = timestampWithTimeZone("cancel_requested_at").nullable()
    val createdAt = timestampWithTimeZone("created_at")
    val updatedAt = timestampWithTimeZone("updated_at")
    override val primaryKey = PrimaryKey(id)
}

/** References returned by completed steps. */
object SagaStepResultTable : Table("saga_step_result") {
    val sagaId = uuid("saga_id")
    val stepIndex = integer("step_index")
    val stepName = text("step_name")
    val output = text("output").nullable()
    val doneAt = timestampWithTimeZone("done_at")
    val compensatedAt = timestampWithTimeZone("compensated_at").nullable()
    override val primaryKey = PrimaryKey(sagaId, stepIndex)
}

/** History: every call, check, compensation and manual action. */
/** Signals received for signal steps: one per name and saga. */
object SagaSignalTable : Table("saga_signal") {
    val sagaId = uuid("saga_id")
    val signalName = text("signal_name")
    val value = text("value")
    val receivedAt = timestampWithTimeZone("received_at")
    override val primaryKey = PrimaryKey(sagaId, signalName)
}

object SagaLogTable : Table("saga_log") {
    val id = long("id").autoIncrement()
    val sagaId = uuid("saga_id")
    val at = timestampWithTimeZone("at")
    val stepIndex = integer("step_index")
    val stepName = text("step_name").nullable()
    val event = text("event")
    val detail = text("detail").nullable()
    val actor = text("actor").nullable()
    val traceId = text("trace_id").nullable()
    override val primaryKey = PrimaryKey(id)
}

/**
 * PostgreSQL implementation with Exposed (DSL). Uses the current Exposed transaction, so
 * [com.example.saga.SagaEngine.create] can run inside the application's own transaction.
 */
class ExposedSagaRepository : SagaRepository {

    /**
     * ON CONFLICT DO NOTHING instead of catching the unique violation: in PostgreSQL an error aborts the
     * whole transaction, and this runs inside the caller's business transaction, which must stay usable
     * after a [DuplicateSagaException] (e.g. to answer 409 and go on).
     */
    override fun insert(record: SagaRecord, now: Instant) {
        val inserted = SagaTable.insertIgnore {
            it[id] = record.id
            it[type] = record.type
            it[businessKey] = record.key
            it[createdAt] = record.createdAt.utc()
            it[input] = record.input                // written once: write() below never touches it
            write(it, record, now)
        }.insertedCount
        if (inserted == 0) throw DuplicateSagaException(record.key)
    }

    override fun lock(id: Uuid, skipLocked: Boolean): SagaRecord? {
        val query = SagaTable.selectAll().where { SagaTable.id eq id }
        val locked = if (skipLocked) {
            query.forUpdate(ForUpdateOption.PostgreSQL.ForUpdate(ForUpdateOption.PostgreSQL.MODE.SKIP_LOCKED))
        } else {
            query.forUpdate()
        }
        return locked.singleOrNull()?.toRecord()
    }

    override fun find(id: Uuid): SagaRecord? =
        SagaTable.selectAll().where { SagaTable.id eq id }.singleOrNull()?.toRecord()

    override fun save(record: SagaRecord, now: Instant) {
        SagaTable.update({ SagaTable.id eq record.id }) { write(it, record, now) }
    }

    override fun findDue(now: Instant, limit: Int, types: Collection<String>): List<Uuid> =
        SagaTable.select(SagaTable.id)
            .where {
                (SagaTable.state inList UNFINISHED) and
                    (SagaTable.type inList types) and
                    (SagaTable.stepStatus neq StepStatus.STUCK.name) and
                    (SagaTable.nextAttemptAt lessEq now.utc())
            }
            .orderBy(SagaTable.nextAttemptAt)
            .limit(limit)
            .map { it[SagaTable.id] }

    override fun results(sagaId: Uuid): Map<String, String?> =
        SagaStepResultTable.selectAll()
            .where { (SagaStepResultTable.sagaId eq sagaId) and SagaStepResultTable.compensatedAt.isNull() }
            .associate { it[SagaStepResultTable.stepName] to it[SagaStepResultTable.output] }

    override fun saveResult(sagaId: Uuid, stepIndex: Int, stepName: String, output: String?, now: Instant) {
        SagaStepResultTable.upsert {
            it[this.sagaId] = sagaId
            it[this.stepIndex] = stepIndex
            it[this.stepName] = stepName
            it[this.output] = output
            it[doneAt] = now.utc()
            it[compensatedAt] = null
        }
    }

    override fun markCompensated(sagaId: Uuid, stepIndex: Int, now: Instant) {
        SagaStepResultTable.update({
            (SagaStepResultTable.sagaId eq sagaId) and (SagaStepResultTable.stepIndex eq stepIndex)
        }) {
            it[compensatedAt] = now.utc()
        }
    }

    override fun log(entry: SagaLogEntry) {
        SagaLogTable.insert {
            it[sagaId] = entry.sagaId
            it[at] = entry.at.utc()
            it[stepIndex] = entry.stepIndex
            it[stepName] = entry.stepName
            it[event] = entry.event
            it[detail] = entry.detail?.take(MAX_TEXT)
            it[actor] = entry.actor
            it[traceId] = entry.traceId
        }
    }

    private fun write(s: UpdateBuilder<*>, r: SagaRecord, now: Instant) {
        s[SagaTable.state] = r.state.name
        s[SagaTable.stepIndex] = r.stepIndex
        s[SagaTable.stepStatus] = r.stepStatus.name
        s[SagaTable.attempts] = r.attempts
        s[SagaTable.checkFailures] = r.checkFailures
        s[SagaTable.cancelRequestedAt] = r.cancelRequestedAt?.utc()
        s[SagaTable.nextAttemptAt] = r.nextAttemptAt.utc()
        s[SagaTable.lockedUntil] = r.lockedUntil?.utc()
        s[SagaTable.lastError] = r.lastError?.take(MAX_TEXT)
        s[SagaTable.traceparent] = r.traceparent
        s[SagaTable.updatedAt] = now.utc()
    }

    private fun ResultRow.toRecord() = SagaRecord(
        id = this[SagaTable.id],
        type = this[SagaTable.type],
        key = this[SagaTable.businessKey],
        state = SagaState.valueOf(this[SagaTable.state]),
        stepIndex = this[SagaTable.stepIndex],
        stepStatus = StepStatus.valueOf(this[SagaTable.stepStatus]),
        attempts = this[SagaTable.attempts],
        checkFailures = this[SagaTable.checkFailures],
        nextAttemptAt = this[SagaTable.nextAttemptAt].toKotlin(),
        lockedUntil = this[SagaTable.lockedUntil]?.toKotlin(),
        lastError = this[SagaTable.lastError],
        traceparent = this[SagaTable.traceparent],
        createdAt = this[SagaTable.createdAt].toKotlin(),
        input = this[SagaTable.input],
        cancelRequestedAt = this[SagaTable.cancelRequestedAt]?.toKotlin(),
    )

    override fun purgeFinished(before: Instant, limit: Int): Int {
        // SKIP LOCKED: a row locked by anyone else is simply left for the next run.
        val ids = SagaTable.select(SagaTable.id)
            .where { (SagaTable.state inList FINISHED) and (SagaTable.updatedAt less before.utc()) }
            .orderBy(SagaTable.updatedAt)
            .limit(limit)
            .forUpdate(ForUpdateOption.PostgreSQL.ForUpdate(ForUpdateOption.PostgreSQL.MODE.SKIP_LOCKED))
            .map { it[SagaTable.id] }
        if (ids.isEmpty()) return 0
        // Children first: saga_log and saga_step_result reference saga.
        SagaLogTable.deleteWhere { SagaLogTable.sagaId inList ids }
        SagaSignalTable.deleteWhere { SagaSignalTable.sagaId inList ids }
        SagaStepResultTable.deleteWhere { SagaStepResultTable.sagaId inList ids }
        return SagaTable.deleteWhere { SagaTable.id inList ids }
    }

    override fun saveSignal(sagaId: Uuid, name: String, value: String, now: Instant): Boolean =
        SagaSignalTable.insertIgnore {                 // ON CONFLICT DO NOTHING: the first signal of a name wins
            it[this.sagaId] = sagaId
            it[signalName] = name
            it[this.value] = value
            it[receivedAt] = now.utc()
        }.insertedCount > 0

    override fun signal(sagaId: Uuid, name: String): String? =
        SagaSignalTable.select(SagaSignalTable.value)
            .where { (SagaSignalTable.sagaId eq sagaId) and (SagaSignalTable.signalName eq name) }
            .singleOrNull()
            ?.get(SagaSignalTable.value)

    private companion object {
        const val MAX_TEXT = 2000
        val UNFINISHED = listOf(SagaState.RUNNING.name, SagaState.COMPENSATING.name)
        val FINISHED = listOf(SagaState.COMPLETED.name, SagaState.FAILED.name)
    }
}

// timestampWithTimeZone is java.time.OffsetDateTime, even in exposed-kotlin-datetime (its timestamp() is
// kotlin.time.Instant but maps to a column WITHOUT time zone, unlike the timestamptz schema): convert here.
private fun Instant.utc(): OffsetDateTime = toJavaInstant().atOffset(ZoneOffset.UTC)

private fun OffsetDateTime.toKotlin(): Instant = toInstant().toKotlinInstant()
